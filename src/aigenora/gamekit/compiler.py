def has_game_blueprint(spec: Any) -> bool:
    if not isinstance(spec, dict):
        return False
    rules = spec.get("rules")
    return isinstance(rules, dict) and isinstance(rules.get("game_kit"), dict)


def inspect_game_spec(spec_or_path: dict[str, Any] | str | Path) -> dict[str, Any]:
    if isinstance(spec_or_path, dict):
        spec = copy.deepcopy(spec_or_path)
    else:
        source = Path(spec_or_path)
        if source.is_dir():
            source = source / "spec.json"
        spec = load_spec(source)
    protocol_id = protocol_hash_from_obj(spec)
    if not has_game_blueprint(spec):
        return {
            "schema": BUILD_MARKER_SCHEMA,
            "status": "not_game_kit",
            "recognized": False,
            "protocol_id": protocol_id,
            "supported_presets": list(SUPPORTED_PRESETS),
        }
    try:
        game = _game_config_from_spec(spec)
    except GameKitError as exc:
        return {
            "schema": BUILD_MARKER_SCHEMA,
            "status": "unsupported",
            "recognized": True,
            "protocol_id": protocol_id,
            "reason": str(exc),
            "supported_presets": list(SUPPORTED_PRESETS),
        }
    return {
        "schema": BUILD_MARKER_SCHEMA,
        "status": "ready",
        "recognized": True,
        "protocol_id": protocol_id,
        "preset": game["preset"],
        "name": game["name"],
        "players": game["players"],
        "theme": game["theme"],
        "materialization": "deterministic_local_runtime_v1",
        "requires_remote_code": False,
    }


def _sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _write_text_atomic(path: Path, value: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary_value = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_value)
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(value)
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def _read_marker(protocol_dir: Path) -> dict[str, Any] | None:
    try:
        value = json.loads((protocol_dir / BUILD_MARKER).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return value if isinstance(value, dict) else None


def materialize_protocol(
    protocol_dir: str | Path,
    *,
    protocol_id: str | None = None,
    include_ui: bool = True,
    force: bool = False,
    run_smoke: bool = False,
) -> dict[str, Any]:
    """Materialize trusted local hooks/UI from a content-addressed Game Kit spec.

    No executable bytes are accepted from the protocol author. Existing custom hooks
    are preserved; only a pristine generated skeleton or a prior matching Game Kit
    build can be replaced.
    """

    started = time.perf_counter()
    root = Path(protocol_dir).resolve()
    spec_path = root / "spec.json"
    if not spec_path.is_file():
        raise GameKitError(f"spec.json not found: {spec_path}")
    spec = load_spec(spec_path)
    actual_protocol_id = protocol_hash_from_obj(spec)
    if protocol_id is not None and protocol_id != actual_protocol_id:
        raise GameKitError(
            f"protocol hash mismatch: expected {protocol_id}, got {actual_protocol_id}"
        )
    game = _game_config_from_spec(spec)
    hooks_text = _render_hooks(game)
    ui_text = _render_ui(game)
    compile(hooks_text, str(root / "hooks.py"), "exec")
    hooks_methods, supported_control_modes = _inspect_generated_hooks(
        game, hooks_text.encode("utf-8")
    )
    existing_marker = _read_marker(root)
    matching_build = bool(
        existing_marker
        and existing_marker.get("schema") == BUILD_MARKER_SCHEMA
        and existing_marker.get("protocol_id") == actual_protocol_id
    )
    hooks_path = root / "hooks.py"
    hooks_status = "unchanged"
    if hooks_path.exists():
        existing_hooks = hooks_path.read_text(encoding="utf-8")
        if existing_hooks != hooks_text:
            from aigenora.agent.skeleton import detect_pristine

            pristine = bool(detect_pristine(root).get("pristine"))
            generated_hashes = (
                existing_marker.get("generated_hashes")
                if isinstance(existing_marker, dict)
                else None
            )
            unmodified_build = bool(
                matching_build
                and isinstance(generated_hashes, dict)
                and generated_hashes.get("hooks.py") == _sha256_text(existing_hooks)
            )
            if not (pristine or unmodified_build or force):
                raise GameKitError(
                    f"refusing to overwrite custom hooks.py in {root}"
                )
            _write_text_atomic(hooks_path, hooks_text)
            hooks_status = "replaced_pristine" if pristine else "updated"
    else:
        _write_text_atomic(hooks_path, hooks_text)
        hooks_status = "created"

    ui_status = "skipped"
    ui_path = root / "ui" / "index.html"
    if include_ui:
        if not ui_path.exists():
            _write_text_atomic(ui_path, ui_text)
            ui_status = "created"
        elif ui_path.read_text(encoding="utf-8") == ui_text:
            ui_status = "unchanged"
        elif (
            matching_build
            and isinstance(existing_marker.get("generated_hashes"), dict)
            and existing_marker["generated_hashes"].get("ui/index.html")
            == _sha256_text(ui_path.read_text(encoding="utf-8"))
        ) or force:
            _write_text_atomic(ui_path, ui_text)
            ui_status = "updated"
        else:
            ui_status = "preserved_existing"

    marker = _marker(actual_protocol_id, game)
    marker["generated_hashes"] = {
        "hooks.py": _sha256_text(hooks_text),
        "ui/index.html": _sha256_text(ui_text),
    }
    _write_text_atomic(
        root / BUILD_MARKER,
        json.dumps(marker, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
    )
    smoke = _smoke_game_bundle(root) if run_smoke else {"status": "skipped"}
    return {
        "schema": BUILD_MARKER_SCHEMA,
        "status": "materialized",
        "source_kind": "local_blueprint",
        "protocol_id": actual_protocol_id,
        "preset": game["preset"],
        "name": game["name"],
        "hooks": hooks_status,
        "ui": ui_status,
        "hooks_methods": hooks_methods,
        "supported_control_modes": supported_control_modes,
        "smoke": smoke,
        "elapsed_ms": round((time.perf_counter() - started) * 1000, 3),
    }


def _assert_replaceable(output: Path) -> None:
    if output.is_symlink():
        raise GameKitError("refusing to replace a symlinked output directory")
    marker_path = output / BUILD_MARKER
    try:
        marker = json.loads(marker_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise GameKitError(
            f"refusing to replace an unmarked directory: {output}"
        ) from exc
    if marker.get("schema") != BUILD_MARKER_SCHEMA:
        raise GameKitError(f"refusing to replace an unknown build directory: {output}")


def _install_stage(stage: Path, output: Path, *, force: bool) -> None:
    if not output.exists():
        os.replace(stage, output)
        return
    if not force:
        raise GameKitError(f"output already exists; pass --force to replace it: {output}")
    _assert_replaceable(output)
    backup = output.with_name(f".{output.name}.game-kit-backup-{uuid.uuid4().hex}")
    os.replace(output, backup)
    try:
        os.replace(stage, output)
    except Exception:
        os.replace(backup, output)
        raise
    shutil.rmtree(backup)


def _game_config_from_spec(spec: dict[str, Any]) -> dict[str, Any]:
    rules = spec.get("rules")
    config = rules.get("game_kit") if isinstance(rules, dict) else None
    normalized = normalize_manifest(config)
    if normalized != config:
        raise GameKitError("rules.game_kit must be a fully normalized manifest")
    return normalized


def _next_target(state: dict[str, Any], actor: str) -> str | None:
    order = list(state.get("turn_order") or [])
    if actor not in order:
        return None
    start = order.index(actor)
    players = state.get("players") or {}
    for offset in range(1, len(order) + 1):
        candidate = order[(start + offset) % len(order)]
        if candidate != actor and (players.get(candidate) or {}).get("alive") is True:
            return candidate
    return None


def choose_preview_action(state: dict[str, Any]) -> dict[str, Any]:
    actor = str(state.get("current_player") or "")
    player = (state.get("players") or {}).get(actor) or {}
    game = state.get("game") or {}
    energy = int(player.get("energy", 0))
    actions = list(game.get("actions") or [])
    affordable = [item for item in actions if int(item.get("cost", 0)) <= energy]
    damage = [
        item
        for item in affordable
        if item.get("effect") in {"damage", "damage_all"}
    ]
    selected = (damage or affordable)[0]
    action: dict[str, Any] = {"kind": "play", "move": selected["id"]}
    if selected.get("effect") == "damage":
        target = _next_target(state, actor)
        if target:
            action["target_public_key"] = target
    return action


def _smoke_duel_bundle(protocol_dir: Path) -> dict[str, Any]:
    started = time.perf_counter()
    spec = load_spec(protocol_dir / "spec.json")
    config = _game_config_from_spec(spec)
    with tempfile.TemporaryDirectory(prefix="aigenora-game-kit-smoke-") as root_value:
        root = Path(root_value)
        keys = [
            keygen(str(root / f"member-{index}"), force=True)
            for index in range(int(config["players"]))
        ]
        members = [
            {
                "member_id": f"member-{index}",
                "public_key": key.public_key,
                "seat": index,
                "status": "active",
            }
            for index, key in enumerate(keys)
        ]
        authority = GroupAuthority(
            spec=spec,
            hooks=load_hooks(protocol_dir),
            options={},
            state_dir=root / "leader-0",
            group_id="game-kit-smoke",
            leader_public_key=keys[0].public_key,
            leader_epoch=0,
            membership_version=len(members),
            members=members,
            keypair=keys[0],
        )
        migrations = 0
        turns = 0
        maximum = int(config["combat"]["max_turns"]) + len(members) * 2
        while not authority.completed and turns < maximum:
            actor = str(authority.state["current_player"])
            action = choose_preview_action(authority.state)
            _envelopes, receipt = authority.apply_input(
                actor_public_key=actor,
                client_seq=authority.last_client_seq.get(actor, 0) + 1,
                action=action,
            )
            if receipt.get("status") != "accepted":
                raise GameKitError("generated game smoke action was not accepted")
            turns += 1
            if turns == 2 and not authority.completed:
                checkpoint = authority.checkpoint()
                authority = GroupAuthority(
                    spec=spec,
                    hooks=load_hooks(protocol_dir),
                    options={},
                    state_dir=root / "leader-1",
                    group_id="game-kit-smoke",
                    leader_public_key=keys[1].public_key,
                    leader_epoch=1,
                    membership_version=len(members),
                    members=members,
                    keypair=keys[1],
                    checkpoint=checkpoint,
                )
                migrations += 1
        if not authority.completed or not authority.outcome:
            raise GameKitError("generated game smoke did not reach a terminal outcome")
        return {
            "status": "passed",
            "turns": turns,
            "outcome": authority.outcome,
            "leader_migrations": migrations,
            "final_seq": authority.seq,
            "elapsed_ms": round((time.perf_counter() - started) * 1000, 3),
        }


def _smoke_matrix_bundle(protocol_dir: Path) -> dict[str, Any]:
    started = time.perf_counter()
    spec = load_spec(protocol_dir / "spec.json")
    game = _game_config_from_spec(spec)
    with tempfile.TemporaryDirectory(prefix="aigenora-game-kit-matrix-") as root_value:
        root = Path(root_value)
        host = load_hooks(protocol_dir)
        guest = load_hooks(protocol_dir)
        host.proto_init({}, "host", [], root / "host", {"mode": "auto"})
        guest.proto_init({}, "guest", [], root / "guest", {"mode": "auto"})
        choices = [item["id"] for item in game["choices"]]
        rounds = 0
        completed = False
        outcome = "none"
        while rounds < int(game["match"]["max_rounds"]):
            host_value = choices[rounds % len(choices)]
            guest_value = choices[(rounds + 1) % len(choices)]
            result = host.proto_round_judge(rounds, host_value, guest_value, {})
            if not isinstance(result.response, dict):
                raise GameKitError("generated choice matrix judge returned no response")
            guest.proto_guest_handle(result.response)
            rounds += 1
            if result.completed:
                completed = True
                outcome = str(result.response.get("game_winner") or "none")
                break
        if not completed or outcome == "none":
            raise GameKitError("generated choice matrix smoke did not complete")
        return {
            "status": "passed",
            "rounds": rounds,
            "outcome": outcome,
            "commit_reveal_contract": True,
            "elapsed_ms": round((time.perf_counter() - started) * 1000, 3),
        }


def _smoke_arcade_bundle(protocol_dir: Path) -> dict[str, Any]:
    started = time.perf_counter()
    spec = load_spec(protocol_dir / "spec.json")
    game = _game_config_from_spec(spec)
    with tempfile.TemporaryDirectory(prefix="aigenora-game-kit-arcade-") as root_value:
        root = Path(root_value)
        host = load_hooks(protocol_dir)
        guest = load_hooks(protocol_dir)
        host.proto_init({}, "host", [], root / "host", {"mode": "auto"})
        guest.proto_init({}, "guest", [], root / "guest", {"mode": "auto"})
        state = host.proto_realtime_initial_state()
        outcome = "none"
        ticks = 0
        for tick in range(1, int(game["victory"]["max_ticks"]) + 1):
            host_commands = host.proto_realtime_validate_commands(
                "host", host.proto_realtime_commands(state, tick), state, tick
            )
            guest_commands = guest.proto_realtime_validate_commands(
                "guest", guest.proto_realtime_commands(state, tick), state, tick
            )
            step = host.proto_realtime_step(
                state,
                tick,
                {"host": host_commands, "guest": guest_commands},
            )
            state = step["state"]
            outcome = str(step.get("outcome") or "none")
            ticks = tick
            if outcome != "none":
                break
        if outcome == "none" or not state.get("game_over"):
            raise GameKitError("generated arcade smoke did not complete")
        audit = host.proto_realtime_audit_outcome(
            {"state": state, "outcome": outcome, "events": state.get("events") or []}
        )
        if audit.get("status") != "passed":
            raise GameKitError("generated arcade terminal audit failed")
        return {
            "status": "passed",
            "ticks": ticks,
            "outcome": outcome,
            "vehicle": game["vehicle"]["kind"],
            "movement": game["vehicle"]["movement"],
            "pickups": list(game["pickups"]),
            "elapsed_ms": round((time.perf_counter() - started) * 1000, 3),
        }


def _smoke_game_bundle(protocol_dir: Path) -> dict[str, Any]:
    spec = load_spec(protocol_dir / "spec.json")
    preset = _game_config_from_spec(spec)["preset"]
    if preset == "duel":
        return _smoke_duel_bundle(protocol_dir)
    if preset == "choice-matrix":
        return _smoke_matrix_bundle(protocol_dir)
    if preset == "arcade":
        return _smoke_arcade_bundle(protocol_dir)
    raise GameKitError(f"unsupported preset: {preset}")


def validate_game_bundle(
    protocol_dir: str | Path,
    *,
    run_smoke: bool = True,
) -> dict[str, Any]:
    started = time.perf_counter()
    root = Path(protocol_dir).resolve()
    spec_path = root / "spec.json"
    hooks_path = root / "hooks.py"
    ui_path = root / "ui" / "index.html"
    for required in (spec_path, hooks_path, ui_path):
        if not required.is_file():
            raise GameKitError(f"generated game is missing {required.relative_to(root)}")
    spec = load_spec(spec_path)
    config = _game_config_from_spec(spec)
    hooks_source = hooks_path.read_bytes()
    compile(hooks_source.decode("utf-8"), str(hooks_path), "exec")
    hooks_methods, supported_control_modes = _inspect_generated_hooks(
        config, hooks_source
    )
    ui = ui_path.read_text(encoding="utf-8")
    for marker in (
        "parent.postMessage",
        'type:"hello"',
        "@media",
        "data-theme",
    ):
        if marker not in ui:
            raise GameKitError(f"generated UI is missing bridge marker: {marker}")
    bridge_marker = {
        "duel": 'request("action"',
        "choice-matrix": 'request("decide"',
        "arcade": 'request("orders"',
    }[config["preset"]]
    if bridge_marker not in ui:
        raise GameKitError(f"generated UI is missing bridge marker: {bridge_marker}")
    if "http://" in ui or "https://" in ui:
        raise GameKitError("generated UI must not load external resources")
    protocol_id = protocol_hash_from_obj(spec)
    smoke = _smoke_game_bundle(root) if run_smoke else {"status": "skipped"}
    return {
        "schema": BUILD_MARKER_SCHEMA,
        "status": "passed",
        "preset": config["preset"],
        "protocol_id": protocol_id,
        "players": config["players"],
        "theme": config["theme"],
        "files": ["hooks.py", "spec.json", "ui/index.html"],
        "hooks_methods": hooks_methods,
        "supported_control_modes": supported_control_modes,
        "smoke": smoke,
        "elapsed_ms": round((time.perf_counter() - started) * 1000, 3),
    }


def compile_game(
    output: str | Path,
    manifest: dict[str, Any] | None = None,
    *,
    force: bool = False,
) -> dict[str, Any]:
    started = time.perf_counter()
    normalized = normalize_manifest(manifest or {})
    spec = _build_spec(normalized)
    protocol_id = protocol_hash_from_obj(spec)
    destination = Path(output).resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(
        tempfile.mkdtemp(prefix=".aigenora-game-kit-", dir=destination.parent)
    )
    installed = False
    try:
        (stage / "ui").mkdir()
        hooks_text = _render_hooks(normalized)
        ui_text = _render_ui(normalized)
        (stage / "spec.json").write_text(
            json.dumps(spec, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        (stage / "hooks.py").write_text(
            hooks_text, encoding="utf-8", newline="\n"
        )
        (stage / "ui" / "index.html").write_text(
            ui_text, encoding="utf-8", newline="\n"
        )
        validation = validate_game_bundle(stage, run_smoke=True)
        marker = _marker(protocol_id, normalized)
        marker["generated_hashes"] = {
            "hooks.py": _sha256_text(hooks_text),
            "ui/index.html": _sha256_text(ui_text),
        }
        (stage / BUILD_MARKER).write_text(
            json.dumps(
                marker,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )
        _install_stage(stage, destination, force=force)
        installed = True
    finally:
        if not installed and stage.exists():
            shutil.rmtree(stage, ignore_errors=True)
    elapsed_ms = round((time.perf_counter() - started) * 1000, 3)
    host_control_mode = "hybrid" if normalized["preset"] == "arcade" else "human"
    return {
        **validation,
        "output": str(destination),
        "elapsed_ms": elapsed_ms,
        "next": {
            "test": f'python -m aigenora protocol test "{destination}"',
            "host": (
                f'python -m aigenora host --protocol-dir "{destination}" '
                f"--control-mode {host_control_mode} --web auto"
            ),
            "friend_join": (
                "Publish a normal invitation without --share-bundle; "
                "the Guest materializes Game Kit locally from spec.json."
            ),
        },
    }

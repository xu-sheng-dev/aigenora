def _asset_text(relative: str) -> str:
    asset = resources.files("aigenora.gamekit").joinpath("templates", relative)
    return asset.read_text(encoding="utf-8")


def _render_hooks(manifest: dict[str, Any]) -> str:
    preset = manifest["preset"]
    if preset in {"duel", "choice-matrix"}:
        return _asset_text(f"{preset}/hooks.py.txt")
    if preset == "arcade":
        blueprint = pprint.pformat(manifest, sort_dicts=True, width=100)
        return (
            "from __future__ import annotations\n\n"
            "from aigenora.gamekit.runtimes.arcade_v1 import ArcadeRuntimeV1\n"
            "from aigenora.proto.hooks import ProtocolHooks\n\n\n"
            "class Hooks(ArcadeRuntimeV1, ProtocolHooks):\n"
            "    SUPPORTED_CONTROL_MODES = (\"autonomous\", \"hybrid\")\n"
            f"    BLUEPRINT = {blueprint}\n"
        )
    raise GameKitError(f"unsupported preset: {preset}")


def _inspect_generated_hooks(
    manifest: dict[str, Any], hooks_source: bytes
) -> tuple[list[str], list[str]]:
    if manifest["preset"] == "arcade":
        # The Arcade adapter can import the trusted local runtime, but received
        # P2P hooks cannot. Keep those two capability boundaries independent.
        if hooks_source != _render_hooks(manifest).encode("utf-8"):
            raise GameKitError(
                "generated arcade adapter differs from the trusted template"
            )
        from aigenora.gamekit.runtimes.arcade_v1 import ArcadeRuntimeV1

        methods = sorted(
            name
            for name in dir(ArcadeRuntimeV1)
            if name.startswith("proto_")
            and callable(getattr(ArcadeRuntimeV1, name))
        )
        modes = ["autonomous", "hybrid"]
        return methods, modes

    # Standalone templates also satisfy the stricter received-bundle source
    # contract, which catches accidental capability expansion.
    from aigenora.agent.protocol_bundle import inspect_hooks_source

    inspection = inspect_hooks_source(hooks_source)
    return list(inspection.methods), list(inspection.supported_control_modes)


